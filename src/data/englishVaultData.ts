export interface ReviewCardRecord {
  stage: 0 | 1 | 2 | 3; // 0: New/Lapsed, 1: Learning (1d), 2: Reviewing (3d), 3: Mastered (7d+)
  nextReviewAt: number;
  reps: number;
}

export const DAY_MS = 24 * 60 * 60 * 1000;

export function scheduleCardReview(
  prev: ReviewCardRecord | undefined,
  rating: 'again' | 'hard' | 'good',
  now = Date.now()
): ReviewCardRecord {
  const reps = (prev?.reps ?? 0) + 1;
  if (rating === 'again') {
    return {
      stage: 0,
      nextReviewAt: now, // Due immediately
      reps,
    };
  }
  if (rating === 'hard') {
    const nextStage: 1 | 2 = prev && prev.stage >= 2 ? 2 : 1;
    return {
      stage: nextStage,
      nextReviewAt: now + 1 * DAY_MS,
      reps,
    };
  }
  // 'good'
  const currentStage = prev?.stage ?? 0;
  const nextStage = (Math.min(3, currentStage + 1) as 1 | 2 | 3);
  const days = nextStage === 1 ? 1 : nextStage === 2 ? 3 : 7;
  return {
    stage: nextStage,
    nextReviewAt: now + days * DAY_MS,
    reps,
  };
}

/**
 * Anki / Eudic (欧路词典) / Quizlet compatible Tab-Delimited .txt export
 */
export function formatVaultAsTsv(items: VaultVocabItem[], isZh: boolean): string {
  const header = '#word\tipa\tpos\tmeaning\tcollocation\texample\ttrack';
  const rows = items.map((item) => {
    const meaning = isZh ? item.meaning : item.meaningEn;
    const example = isZh ? `${item.exampleEn} (${item.exampleZh})` : item.exampleEn;
    const book = isZh ? item.bookName : item.bookNameEn;
    return [
      item.word,
      item.ipa,
      item.pos,
      meaning,
      item.collocation,
      example,
      book,
    ]
      .map((cell) => String(cell).replace(/[\t\r\n]+/g, ' ').trim())
      .join('\t');
  });
  return [header, ...rows].join('\n');
}

function escapeCsvCell(val: string): string {
  const clean = String(val).replace(/\r?\n/g, ' ').trim();
  if (/[",]/.test(clean)) {
    return `"${clean.replace(/"/g, '""')}"`;
  }
  return clean;
}

/**
 * Excel / WPS compatible UTF-8 BOM CSV export
 */
export function formatVaultAsCsv(items: VaultVocabItem[], isZh: boolean): string {
  const header = ['Word', 'IPA', 'POS', 'Meaning', 'Collocation', 'Root/Memory', 'Example', 'Track']
    .map(escapeCsvCell)
    .join(',');
  const rows = items.map((item) =>
    [
      item.word,
      item.ipa,
      item.pos,
      isZh ? item.meaning : item.meaningEn,
      item.collocation,
      isZh ? item.rootHint : item.rootHintEn,
      isZh ? `${item.exampleEn} | ${item.exampleZh}` : item.exampleEn,
      isZh ? item.bookName : item.bookNameEn,
    ]
      .map(escapeCsvCell)
      .join(',')
  );
  return '\uFEFF' + [header, ...rows].join('\n');
}

export function triggerTextDownload(
  filename: string,
  content: string,
  mimeType = 'text/plain;charset=utf-8'
): void {
  if (typeof document === 'undefined' || typeof URL === 'undefined') return;
  const blob = new Blob([content], { type: mimeType });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  a.style.display = 'none';
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  window.setTimeout(() => {
    try {
      URL.revokeObjectURL(url);
    } catch {}
  }, 1500);
}
