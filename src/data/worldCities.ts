export function countryCodeToFlag(code?: string): string {
  if (!code || code.length !== 2) return '🌍';
  const upper = code.toUpperCase();
  const pts = [...upper].map((c) => 127397 + c.charCodeAt(0));
  try {
    return String.fromCodePoint(...pts);
  } catch {
    return '🌍';
  }
}

export function matchWorldCity(city: CityTimeInfo, rawQuery: string): boolean {
  const q = normalizeSearchText(rawQuery);
  if (!q) return true;
  const qCompact = q.replace(/[\s,.-]+/g, '');

  const fields = [
    city.nameZh,
    city.nameTw || '',
    city.nameEn,
    city.shortNameZh,
    city.shortNameTw || '',
    city.shortNameEn,
    city.countryZh,
    city.countryTw || '',
    city.countryEn,
    city.timeZone,
    city.id,
    ...(city.aliases || []),
  ];

  for (const field of fields) {
    const norm = normalizeSearchText(field);
    if (!norm) continue;
    if (norm.includes(q)) return true;
    if (qCompact.length >= 2 && norm.replace(/[\s,.-]+/g, '').includes(qCompact)) {
      return true;
    }
  }

  const offsetStr = `${city.utcOffset >= 0 ? '+' : ''}${city.utcOffset}`;
  const tzLabels = [`utc${offsetStr}`, `gmt${offsetStr}`, offsetStr];
  return tzLabels.some((lbl) => lbl.includes(qCompact));
}
