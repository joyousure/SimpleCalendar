export function normalizeSearchText(input: string): string {
  const folded = input
    .normalize('NFKD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLowerCase()
    .trim();
  let out = '';
  for (const ch of folded) {
    out += CJK_SIMPLIFY_MAP[ch] || ch;
  }
  return out;
}

